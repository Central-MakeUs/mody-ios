import Foundation
import ProjectDescription

public extension Workspace {
    static func mody(manifestPath: String) throws -> Workspace {
        // make generate disables manifest caching so JSON-only changes are reloaded.
        let configurationURL = URL(fileURLWithPath: manifestPath)
            .deletingLastPathComponent()
            .appendingPathComponent("Test/Settings/TestConfiguration.json")
        let testModules = try JSONDecoder()
            .decode(TestConfiguration.self, from: Data(contentsOf: configurationURL))
            .modules.filter(\.enabled)
        let implementationTargets: [TargetReference] = testModules.map {
            .project(path: .relativeToManifest($0.projectPath), target: $0.name)
        }
        let testTargets: [TargetReference] = testModules.map {
            .project(path: .relativeToManifest($0.projectPath), target: "\($0.name)Tests")
        }

        return Workspace(
            name: projectEnvironment.appName,
            projects: ["Projects/App"] + testModules
                .filter { $0.projectPath != "Projects/App" }
                .map { .relativeToManifest($0.projectPath) },
            schemes: [
                .allTests(
                    implementationTargets: implementationTargets,
                    testTargets: testTargets
                )
            ],
            generationOptions: .options(autogeneratedWorkspaceSchemes: .disabled)
        )
    }
}

private struct TestConfiguration: Decodable {
    struct Module: Decodable {
        let name: String
        let projectPath: String
        let enabled: Bool
    }

    let modules: [Module]
}
