public enum OnBoardingAgreementDocument: Equatable {
    case privacyPolicy
    case termsOfService

    var title: String {
        switch self {
        case .privacyPolicy:
            return "개인정보처리방침"
        case .termsOfService:
            return "이용약관"
        }
    }

    var sections: [OnBoardingAgreementSection] {
        switch self {
        case .privacyPolicy:
            return OnBoardingAgreementConstants.privacyPolicySections
        case .termsOfService:
            return OnBoardingAgreementConstants.termsOfServiceSections
        }
    }

    var effectiveDateNotice: String {
        OnBoardingAgreementConstants.effectiveDateNotice
    }
}

